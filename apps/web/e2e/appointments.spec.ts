import {test,expect} from '@playwright/test';
test('Admin schedules clinics and Reception appointment flow retains identity and history',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const local=new Date(new Date().toLocaleString('en-US',{timeZone:'Asia/Kolkata'}));
  const day=new Date().toLocaleDateString('en-CA',{timeZone:'Asia/Kolkata'});
  const weekday=String((local.getDay()+6)%7);
  await page.goto('/login');
  await page.getByLabel('Username',{exact:true}).fill(process.env.STAFF_ADMIN_USERNAME||'admin');
  await page.getByLabel('Password',{exact:true}).fill(process.env.STAFF_ADMIN_PASSWORD||'Browser!Admin2026');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('link',{name:'Appointments',exact:true}).click();
  await page.getByRole('link',{name:'Doctor schedules',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Doctor schedules',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Add clinic window',exact:true}).click();
  const window=page.getByRole('dialog',{name:'Clinic window',exact:true});
  await window.getByLabel('Schedule branch',{exact:true}).selectOption({label:'Paloura'});
  await window.getByLabel('Day of week',{exact:true}).selectOption(weekday);
  await window.getByLabel('Start time (IST)',{exact:true}).fill('00:00');
  await window.getByLabel('End time (IST)',{exact:true}).fill('23:59');
  await window.getByLabel('Effective from',{exact:true}).fill(day);
  await window.getByLabel('Effective until',{exact:true}).fill(day);
  await window.getByLabel('Reason for schedule change',{exact:true}).fill('Isolated fictional browser UAT clinic');
  await window.getByRole('button',{name:'Save clinic window',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Doctor schedule saved');
  await page.getByRole('button',{name:'Add schedule exception',exact:true}).click();
  const exception=page.getByRole('dialog',{name:'Schedule exception',exact:true});
  await exception.getByLabel('Exception branch',{exact:true}).selectOption({label:'Paloura'});
  await exception.getByLabel('Exception type',{exact:true}).selectOption('BREAK');
  await exception.getByLabel('Exception start time',{exact:true}).fill('00:00');
  await exception.getByLabel('Exception end time',{exact:true}).fill('00:15');
  await exception.getByLabel('Exception reason',{exact:true}).fill('Fictional short clinic break');
  await exception.getByRole('button',{name:'Save schedule exception',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Schedule exception saved');
  await page.getByRole('row').filter({hasText:'Fictional short clinic break'}).getByRole('button',{name:'Cancel exception',exact:true}).click();
  const cancel=page.getByRole('dialog',{name:'Cancel schedule exception',exact:true});
  await cancel.getByLabel('Cancellation reason',{exact:true}).fill('Fictional exception cancellation');
  await cancel.getByRole('button',{name:'Confirm cancellation',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Exception cancelled');
  await page.getByRole('link',{name:'Leads',exact:true}).click();
  const person=`Fictional Appointment ${Date.now()}`;
  await page.getByRole('button',{name:'+ New Lead',exact:true}).click();
  const lead=page.getByRole('dialog',{name:'New Lead',exact:true});
  await lead.getByLabel('Name',{exact:true}).fill(person);
  await lead.getByLabel('Mobile',{exact:true}).fill('9876543210');
  await lead.getByLabel('Lead source',{exact:true}).selectOption({index:1});
  await lead.getByLabel('Preferred branch',{exact:true}).selectOption({label:'Paloura'});
  await lead.getByRole('button',{name:'Create Lead',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('No Patient or UHID was created');
  await page.getByRole('link',{name:'Appointments',exact:true}).click();
  async function book(){
    await page.getByRole('button',{name:'+ Book appointment',exact:true}).click();
    const picker=page.getByRole('dialog',{name:'Choose Lead or Patient',exact:true});
    await picker.getByLabel('Find person',{exact:true}).fill(person);
    await picker.getByRole('button',{name:'Search people',exact:true}).click();
    await picker.getByRole('button',{name:new RegExp('^Select '+person)}).click();
    const booking=page.getByRole('dialog',{name:'Book appointment',exact:true});
    await booking.getByLabel('Branch',{exact:true}).selectOption({label:'Paloura'});
    await expect(booking.getByLabel('Available slot (IST)',{exact:true}).locator('option')).not.toHaveCount(1);
    await booking.getByLabel('Available slot (IST)',{exact:true}).selectOption({index:2});
    await booking.getByRole('button',{name:'Confirm appointment',exact:true}).click();
    await expect(page.getByRole('status')).toContainText('Appointment booked');
  }
  await book();
  let row=page.getByRole('row').filter({hasText:person});
  await expect(row.getByText('Lead · no UHID',{exact:true})).toBeVisible();
  await expect(row.getByRole('button',{name:'No show',exact:true})).toBeDisabled();
  await row.getByRole('button',{name:'Reschedule',exact:true}).click();
  const move=page.getByRole('dialog',{name:'Reschedule appointment',exact:true});
  await expect(move.getByLabel('Available slot (IST)',{exact:true}).locator('option')).not.toHaveCount(1);
  await move.getByLabel('Available slot (IST)',{exact:true}).selectOption({index:2});
  await move.getByLabel('Reason for rescheduling',{exact:true}).fill('Fictional requested later slot');
  await move.getByRole('button',{name:'Save reschedule',exact:true}).click();
  await expect(row.getByText('Rescheduled',{exact:true})).toBeVisible();
  await row.getByRole('button',{name:'Cancel appointment',exact:true}).click();
  const reason=page.getByRole('dialog',{name:'Attendance reason',exact:true});
  await reason.getByLabel('Reason',{exact:true}).fill('Fictional cancelled appointment');
  await reason.getByRole('button',{name:'Save attendance change',exact:true}).click();
  await expect(row.getByText('Cancelled',{exact:true})).toBeVisible();
  await row.getByRole('button',{name:'Details',exact:true}).click();
  const details=page.getByRole('region',{name:'Appointment details',exact:true});
  await expect(details.getByText('Fictional requested later slot',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Close details',exact:true}).click();
  await book();
  row=page.getByRole('row').filter({hasText:person}).filter({has:page.getByRole('button',{name:'Mark arrived',exact:true})});
  await row.getByRole('button',{name:'Mark arrived',exact:true}).click();
  const complete=page.getByRole('row').filter({hasText:person}).getByRole('button',{name:'Complete appointment',exact:true});
  await expect(complete).toBeVisible();
  await complete.click();
  await expect(page.getByRole('row').filter({hasText:person}).getByText('Completed',{exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('button',{name:'+ Book appointment',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});
