import {test,expect} from '@playwright/test';
test('Lead register preserves separate inquiries, followups and DNC history',async({page})=>{
  const faults:string[]=[];page.on('pageerror',e=>faults.push(e.message));
  await page.goto('/login');
  await page.getByLabel('Username',{exact:true}).fill(process.env.STAFF_ADMIN_USERNAME||'admin');
  await page.getByLabel('Password',{exact:true}).fill(process.env.STAFF_ADMIN_PASSWORD||'Browser!Admin2026');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('link',{name:'Leads',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Leads',exact:true})).toBeVisible();
  const name=`Fictional Lead ${Date.now()}`;
  await page.getByRole('button',{name:'+ New Lead',exact:true}).click();
  const form=page.getByRole('dialog',{name:'New Lead',exact:true});
  await form.getByLabel('Name',{exact:true}).fill(name);
  await form.getByLabel('Mobile',{exact:true}).fill('9876543210');
  await form.getByLabel('Concern',{exact:true}).fill('Fictional skin inquiry');
  await form.getByLabel('Lead source',{exact:true}).selectOption({index:1});
  await form.getByRole('button',{name:'Create Lead',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('No Patient or UHID was created');
  const row=page.getByRole('row').filter({hasText:name});
  await row.getByRole('button',{name:'Open',exact:true}).click();
  await page.getByRole('button',{name:'Edit Lead / Assign staff',exact:true}).click();
  let edit=page.getByRole('dialog',{name:'Edit Lead',exact:true});
  await expect(edit.getByLabel('Current Lead status')).toContainText('Current status: New');
  const statusChoice=edit.getByLabel('Change Lead status',{exact:true});
  await expect(statusChoice.getByRole('option',{name:/^Converted/})).toHaveAttribute('disabled','');
  await expect(statusChoice.getByRole('option',{name:/^Appointment Booked/})).toHaveAttribute('disabled','');
  await expect(statusChoice.getByRole('option',{name:/^No Show/})).toHaveAttribute('disabled','');
  await expect(statusChoice.getByRole('option',{name:'Do Not Call',exact:true})).toHaveCount(0);
  await expect(page.getByLabel('Status filter',{exact:true}).getByRole('option',{name:'Do Not Call',exact:true})).toHaveCount(0);
  // Native keyboard navigation must skip the workflow-only options at the end.
  const lastStaffStatus=await statusChoice.getByRole('option',{name:'Spam Fake',exact:true}).getAttribute('value');
  await statusChoice.press('End');
  await expect(statusChoice).toHaveValue(lastStaffStatus!);
  await statusChoice.selectOption({label:'New'});
  await edit.getByLabel('Concern',{exact:true}).fill('Updated fictional concern');
  await edit.getByLabel('Assigned staff',{exact:true}).selectOption({label:'Aastha Super Admin'});
  await edit.getByRole('button',{name:'Save Lead',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Lead updated');
  await page.getByRole('button',{name:'Record interaction / Follow-up',exact:true}).click();
  let interaction=page.getByRole('dialog',{name:'Record interaction',exact:true});
  await interaction.getByLabel('Interaction type',{exact:true}).selectOption('FOLLOW_UP');
  await interaction.getByLabel('Summary',{exact:true}).fill('Fictional call back requested');
  await interaction.getByLabel('Next follow-up (IST)',{exact:true}).fill('2026-11-20T11:00');
  await interaction.getByRole('button',{name:'Save to history',exact:true}).click();
  await expect(page.getByText('Fictional call back requested',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Edit Lead / Assign staff',exact:true}).click();
  edit=page.getByRole('dialog',{name:'Edit Lead',exact:true});
  await edit.getByLabel('Change Lead status',{exact:true}).selectOption({label:'Lost'});
  await edit.getByLabel('Lost reason',{exact:true}).selectOption({index:1});
  await edit.getByRole('button',{name:'Save Lead',exact:true}).click();
  await page.getByRole('button',{name:'Edit Lead / Assign staff',exact:true}).click();
  edit=page.getByRole('dialog',{name:'Edit Lead',exact:true});
  await expect(edit.getByLabel('Current Lead status')).toContainText('Current status: Lost');
  await expect(edit.getByLabel('Change Lead status',{exact:true})).toBeDisabled();
  await expect(edit.getByText(/Use Reopen Lead in Lead details/)).toBeVisible();
  await edit.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('button',{name:'Reopen Lead',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Existing Lead reopened');
  await page.getByRole('button',{name:'Mark Do Not Call',exact:true}).click();
  let dnc=page.getByRole('dialog',{name:'DNC change',exact:true});
  await dnc.getByLabel('Reason for DNC change',{exact:true}).fill('Fictional request for no outbound contact');
  await dnc.getByRole('button',{name:'Save to history',exact:true}).click();
  await expect(page.getByText('DNC blocks outbound contact and follow-up scheduling. Inbound contact and internal notes can still be recorded.')).toBeVisible();
  await page.getByRole('button',{name:'Record interaction / Follow-up',exact:true}).click();
  interaction=page.getByRole('dialog',{name:'Record interaction',exact:true});
  await expect(interaction.getByRole('option',{name:'OUTBOUND CALL',exact:true})).toHaveCount(0);
  await interaction.getByLabel('Interaction type',{exact:true}).selectOption('INBOUND_CALL');
  await interaction.getByLabel('Summary',{exact:true}).fill('Fictional inbound inquiry recorded');
  await interaction.getByRole('button',{name:'Save to history',exact:true}).click();
  await expect(page.getByText('Fictional inbound inquiry recorded',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Close Lead',exact:true}).click();
  await page.getByLabel('DNC filter',{exact:true}).selectOption('false');
  await expect(row).toHaveCount(0);
  await page.getByLabel('DNC filter',{exact:true}).selectOption('true');
  await expect(row).toBeVisible();
  await page.getByLabel('Status filter',{exact:true}).selectOption('NEW');
  await expect(row).toHaveCount(0);
  await page.getByLabel('Status filter',{exact:true}).selectOption('FOLLOW_UP_REQUIRED');
  await expect(row).toBeVisible();
  await page.getByLabel('Status filter',{exact:true}).selectOption('');
  await page.getByLabel('DNC filter',{exact:true}).selectOption('');
  await page.getByRole('button',{name:'+ New Lead',exact:true}).click();
  await form.getByLabel('Name' ,{exact:true}).fill(`${name} separate`);
  await form.getByLabel('Mobile',{exact:true}).fill('9876543210');
  await expect(form.getByText('Previous inquiries found',{exact:true})).toBeVisible();
  await form.getByLabel('Concern',{exact:true}).fill('Different fictional inquiry');
  await form.getByLabel('Lead source',{exact:true}).selectOption({index:1});
  await form.getByRole('button',{name:'Create Lead',exact:true}).click();
  await expect(page.getByRole('row').filter({hasText:`${name} separate`})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('button',{name:'+ New Lead',exact:true})).toBeVisible();
  expect(faults).toEqual([]);
});
