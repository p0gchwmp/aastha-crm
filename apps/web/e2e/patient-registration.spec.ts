import {test,expect} from '@playwright/test';

test('Verified registration keeps shared-mobile family identities separate and links later inquiries explicitly',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const name=`Fictional Registration ${Date.now()}`;
  await page.goto('/login');
  await page.getByLabel('Username',{exact:true}).fill(process.env.STAFF_ADMIN_USERNAME||'admin');
  await page.getByLabel('Password',{exact:true}).fill(process.env.STAFF_ADMIN_PASSWORD||'Browser!Admin2026');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  async function lead(person:string){
    await page.getByRole('link',{name:'Leads',exact:true}).click();
    await page.getByRole('button',{name:'+ New Lead',exact:true}).click();
    const form=page.getByRole('dialog',{name:'New Lead',exact:true});
    await form.getByLabel('Name',{exact:true}).fill(person);
    await form.getByLabel('Mobile',{exact:true}).fill('9876543210');
    await form.getByLabel('Age',{exact:true}).fill('35');
    await form.getByLabel('Gender',{exact:true}).selectOption('Female');
    await form.getByLabel('Lead source',{exact:true}).selectOption({index:1});
    await form.getByLabel('Preferred branch',{exact:true}).selectOption({label:'Paloura'});
    await form.getByRole('button',{name:'Create Lead',exact:true}).click();
    const row=page.getByRole('row').filter({hasText:person});
    await row.getByRole('button',{name:'Open',exact:true}).click();
    await page.getByRole('link',{name:'Verified Patient registration',exact:true}).click();
    await expect(page.getByRole('dialog',{name:'Patient registration',exact:true})).toBeVisible();
  }
  await lead(name);
  let form=page.getByRole('dialog',{name:'Patient registration',exact:true});
  await expect(form.getByLabel('DOB',{exact:true})).toHaveValue('');
  await expect(form.getByLabel('Approximate age (years)',{exact:true})).toHaveValue('35');
  await expect(form.getByRole('button',{name:'Create UHID & Convert',exact:true})).toBeDisabled();
  await form.getByLabel('Name',{exact:true}).fill(name+' Verified');
  await form.getByRole('checkbox',{name:'I verified Name, Age/Gender, contact and registration details with the person.',exact:true}).check();
  await form.getByRole('button',{name:'Create UHID & Convert',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Registration saved. UHID:');
  const first=(await page.getByRole('status').innerText()).match(/UHID: ([^.]+)\./)![1];
  await expect(page.getByRole('heading',{name:name+' Verified',exact:true})).toBeVisible();
  await expect(page.getByText('No previous Visits.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Close Patient',exact:true}).click();
  await lead(name+' Second inquiry');
  form=page.getByRole('dialog',{name:'Patient registration',exact:true});
  await expect(form.getByRole('button',{name:`Use Existing ${name} Verified ${first}`,exact:true})).toBeVisible();
  await form.getByRole('button',{name:`Use Existing ${name} Verified ${first}`,exact:true}).click();
  await expect(form.getByRole('button',{name:'Link Lead to Existing Patient',exact:true})).toBeDisabled();
  await form.getByRole('checkbox',{name:'I confirmed Name, Age/Gender and UHID for the selected existing Patient.',exact:true}).check();
  await form.getByRole('button',{name:'Link Lead to Existing Patient',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('UHID: '+first);
  await page.getByRole('button',{name:'Close Patient',exact:true}).click();
  await page.getByRole('button',{name:'+ Register Patient',exact:true}).click();
  form=page.getByRole('dialog',{name:'Patient registration',exact:true});
  await form.getByLabel('Name',{exact:true}).fill(name+' Family member');
  await form.getByLabel('Mobile',{exact:true}).fill('9876543210');
  await form.getByLabel('Approximate age (years)',{exact:true}).fill('28');
  await form.getByLabel('Gender',{exact:true}).selectOption('Male');
  await form.getByRole('button',{name:'Review possible matches',exact:true}).click();
  await expect(form.getByRole('button',{name:`Use Existing ${name} Verified ${first}`,exact:true})).toBeVisible();
  await form.getByRole('checkbox',{name:'I verified the matches and this is a genuinely separate Patient who needs a new UHID.',exact:true}).check();
  await form.getByRole('checkbox',{name:'I verified Name, Age/Gender, contact and registration details with the person.',exact:true}).check();
  await form.getByRole('button',{name:'Register Patient',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Registration saved. UHID:');
  const second=(await page.getByRole('status').innerText()).match(/UHID: ([^.]+)\./)![1];expect(second).not.toBe(first);
  await page.getByRole('button',{name:'Close Patient',exact:true}).click();
  await page.getByPlaceholder('Search UHID, name or mobile',{exact:true}).fill('9876543210');
  await page.getByRole('button',{name:'Search',exact:true}).click();
  await expect(page.getByRole('row').filter({hasText:name+' Verified'})).toContainText(first);
  await expect(page.getByRole('row').filter({hasText:name+' Family member'})).toContainText(second);
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('heading',{name:'Patients',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});
