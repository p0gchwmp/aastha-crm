import {test,expect,Page} from '@playwright/test';
const initial='R3ception!Start2026', personal='R3ception!Private2026', reset='R3ception!Reset2026';
async function login(page:Page,username:string,password:string){
  await page.goto('/login');
  await page.getByLabel('Username',{exact:true}).fill(username);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
}
test('Admin manages reception and first-login passwords are enforced',async({browser})=>{
  const adminContext=await browser.newContext();const admin=await adminContext.newPage();
  const faults:string[]=[];admin.on('pageerror',e=>faults.push(e.message));
  await login(admin,process.env.STAFF_ADMIN_USERNAME||'browser.admin',process.env.STAFF_ADMIN_PASSWORD||'Browser!Admin2026');
  await admin.getByRole('link',{name:'Staff Users',exact:true}).click();
  await expect(admin.getByRole('heading',{name:'Staff Users',exact:true})).toBeVisible();
  await admin.getByRole('button',{name:'Add receptionist',exact:true}).click();
  const username=`uat.reception.${Date.now()}`;
  await admin.getByLabel('Staff name',{exact:true}).fill('Fictional Reception Test');
  await admin.getByRole('textbox',{name:/^Username/}).fill(username);
  await admin.getByLabel('Paloura',{exact:true}).check();
  await admin.getByLabel(/^Temporary password/).fill(initial);
  await admin.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(admin.getByRole('status')).toContainText('Reception account created');
  const row=admin.getByRole('row').filter({hasText:username});await expect(row).toBeVisible();
  const staffContext=await browser.newContext();const staff=await staffContext.newPage();
  staff.on('pageerror',e=>faults.push(e.message));
  await login(staff,username,initial);await expect(staff).toHaveURL(/\/account$/);
  await expect(staff.getByText('Please change your temporary password to access clinic records.')).toBeVisible();
  await staff.getByLabel('Current password',{exact:true}).fill(initial);
  await staff.getByLabel('New password',{exact:true}).fill(personal);
  await staff.getByLabel('Confirm new password',{exact:true}).fill(personal);
  await staff.getByRole('button',{name:'Change password',exact:true}).click();
  await expect(staff).toHaveURL(/\/login\?passwordChanged=1$/);
  await login(staff,username,personal);await expect(staff.getByRole('link',{name:'My Password',exact:true})).toBeVisible();
  await expect(staff.getByRole('link',{name:'Staff Users',exact:true})).toHaveCount(0);
  await admin.reload();
  await row.getByRole('button',{name:'Edit access',exact:true}).click();
  await admin.getByLabel('Role',{exact:true}).selectOption('SUPER_RECEPTIONIST');
  await admin.getByLabel('Paloura',{exact:true}).uncheck();
  await admin.getByRole('checkbox',{name:/^Amphalla/}).check();
  await admin.getByLabel('Reason for change',{exact:true}).fill('UAT branch reassignment');
  await admin.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(admin.getByRole('status')).toContainText('Account updated');
  await row.getByRole('button',{name:'Reset password',exact:true}).click();
  await admin.getByLabel(/^Temporary password/).fill(reset);
  await admin.getByLabel('Reason for change',{exact:true}).fill('UAT reset test');
  await admin.locator('form').getByRole('button',{name:'Reset password',exact:true}).click();
  await expect(admin.getByRole('status')).toContainText('Password reset');
  await staff.goto('/account');await expect(staff).toHaveURL(/\/login$/);
  await login(staff,username,reset);await expect(staff).toHaveURL(/\/account$/);
  await row.getByRole('button',{name:'Edit access',exact:true}).click();
  await admin.getByLabel('Account status',{exact:true}).selectOption('INACTIVE');
  await admin.getByLabel('Reason for change',{exact:true}).fill('UAT complete: disable fictional account');
  await admin.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(row.getByText('Inactive',{exact:true})).toBeVisible();
  await login(staff,username,reset);await expect(staff.getByText('Invalid credentials',{exact:true})).toBeVisible();
  await admin.setViewportSize({width:390,height:844});
  await expect(admin.getByRole('link',{name:'Staff Users',exact:true})).toBeVisible();
  expect(faults).toEqual([]);
  await staffContext.close();await adminContext.close();
});
